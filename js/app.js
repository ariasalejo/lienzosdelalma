const gallery = document.getElementById("gallery");

const filters = document.querySelectorAll(".filter");

const lightbox = document.getElementById("lightbox");

const lightboxImage =
  document.getElementById("lightboxImage");

const lightboxTitle =
  document.getElementById("lightboxTitle");

const lightboxDescription =
  document.getElementById("lightboxDescription");

let currentIndex = 0;

let visibleWorks = [...works];


function renderGallery(list = works) {

  visibleWorks = list;

  gallery.innerHTML = list.map((work, index) => `

    <article
      class="art-card"
      data-category="${work.category}"
      data-index="${index}"
    >

      <a
        class="art-image"
        href="obras/obra-${String(work.id).padStart(2, "0")}.html"
        aria-label="Ver ${work.title}"
      >

        <img
          src="${work.image}"
          alt="${work.title} — Bernardo León Mejía Rivera"
          loading="lazy"
        >

        <span class="art-number">
          ${String(work.id).padStart(2, "0")}
        </span>

        <span class="view">
          Ver obra
        </span>

      </a>

      <div class="art-info">

        <span class="category">
          ${work.category}
        </span>

        <h3>
          ${work.title}
        </h3>

        <p>
          ${work.description}
        </p>

      </div>

    </article>

  `).join("");

  document
    .querySelectorAll(".art-image")
    .forEach((button, index) => {

      button.addEventListener("click", () => {

        openLightbox(index);

      });

    });

}


function openLightbox(index) {

  currentIndex = index;

  const work = visibleWorks[currentIndex];

  lightboxImage.src = work.image;

  lightboxImage.alt = work.title;

  lightboxTitle.textContent =
    `${String(work.id).padStart(2, "0")} · ${work.title}`;

  lightboxDescription.textContent =
    work.description;

  lightbox.classList.add("open");

  lightbox.setAttribute("aria-hidden", "false");

  document.body.classList.add("no-scroll");

}


function closeLightbox() {

  lightbox.classList.remove("open");

  lightbox.setAttribute("aria-hidden", "true");

  document.body.classList.remove("no-scroll");

}


function move(direction) {

  currentIndex =
    (currentIndex + direction + visibleWorks.length)
    % visibleWorks.length;

  openLightbox(currentIndex);

}


filters.forEach(filter => {

  filter.addEventListener("click", () => {

    filters.forEach(item =>
      item.classList.remove("active")
    );

    filter.classList.add("active");

    const value = filter.dataset.filter;

    if (value === "all") {

      renderGallery(works);

    } else {

      renderGallery(
        works.filter(work =>
          work.category === value
        )
      );

    }

  });

});


document
  .getElementById("closeLightbox")
  .addEventListener("click", closeLightbox);


document
  .getElementById("previous")
  .addEventListener("click", () => move(-1));


document
  .getElementById("next")
  .addEventListener("click", () => move(1));


document.addEventListener("keydown", event => {

  if (!lightbox.classList.contains("open")) {
    return;
  }

  if (event.key === "Escape") {
    closeLightbox();
  }

  if (event.key === "ArrowLeft") {
    move(-1);
  }

  if (event.key === "ArrowRight") {
    move(1);
  }

});


lightbox.addEventListener("click", event => {

  if (event.target === lightbox) {
    closeLightbox();
  }

});


const languageButton =
  document.getElementById("language");

let english = false;


languageButton.addEventListener("click", () => {

  english = !english;

  document
    .querySelectorAll("[data-es][data-en]")
    .forEach(element => {

      element.textContent =
        english
          ? element.dataset.en
          : element.dataset.es;

    });

  languageButton.textContent =
    english ? "ES" : "EN";

});


renderGallery();
